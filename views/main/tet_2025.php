    <section class="theme-tet" aria-labelledby="title-theme-tet">
        <h3 id="title-theme-tet">Temáticas principales</h3>
        <ul>
            <li>
            <div class="icon-3d" id="icon-3d-1" aria-hidden="true"></div>
            <article>
                <h4>6G</h4>
                <p>
                Descubre cómo la sexta generación de redes móviles transformará las comunicaciones, integrando 
                inteligencia artificial para lograr mayor velocidad, eficiencia y autonomía, adaptándose a las 
                necesidades de cada usuario.
                </p>
            </article>
            </li>

            <li>
            <div class="icon-3d" id="icon-3d-2" aria-hidden="true"></div>
            <article>
                <h4>Modelos de Lenguaje Extensos (LLM)</h4>
                <p>
                Explora los avances en los Modelos de Lenguaje Extensos (LLMs), tecnología que está redefiniendo 
                la educación, la creatividad y la interacción con la inteligencia artificial, generando texto con 
                naturalidad casi humana.
                </p>
            </article>
            </li>

            <li>
            <div class="icon-3d" id="icon-3d-3" aria-hidden="true"></div>
            <article>
                <h4>Machine Learning</h4>
                <p>
                Adéntrate en el aprendizaje automático, la técnica que permite a las máquinas aprender de los datos, 
                reconocer patrones y tomar decisiones de manera autónoma.
                </p>
            </article>
            </li>

            <li>
            <div class="icon-3d" id="icon-3d-4" aria-hidden="true"></div>
            <article>
                <h4>Deep Learning</h4>
                <p>
                Conoce el Deep Learning, una rama avanzada del aprendizaje automático que utiliza redes neuronales 
                profundas para procesar voz, texto e imágenes con precisión humana.
                </p>
            </article>
            </li>

            <li>
            <div class="icon-3d" id="icon-3d-5" aria-hidden="true"></div>
            <article>
                <h4>Inteligencia Artificial en Videojuegos</h4>
                <p>
                Descubre cómo la inteligencia artificial está revolucionando los videojuegos mediante personajes autónomos, mecánicas dinámicas y entornos virtuales inmersivos.
                </p>
            </article>
            </li>

            <li>
            <div class="icon-3d" id="icon-3d-6" aria-hidden="true"></div>
            <article>
                <h4>Software sostenible: cuando la Ingeniería también piensa en verde</h4>
                <p>
                Crea programas que cuidan el planeta mientras rinden al máximo. Al usar menos energía, optimizar recursos y diseñar pensando en el futuro. La ingeniería no solo innova, sino que también protege el mundo que compartimos, construyendo un futuro tecnológico responsable, limpio y poderoso.
                </p>
            </article>
            </li>
        </ul>

        <div class="container">
            <h2>Preguntas Frecuentes</h2>
            
            <div class="chapters-contact__faq">
                <details class="faq-item">
                    <summary>¿Cuál es la diferencia entre capítulos y sociedades?</summary>
                    <p>Las <strong>sociedades técnicas</strong> son organizaciones globales de IEEE especializadas en áreas específicas (RAS, CS, EDS, WIE). Los <strong>capítulos</strong> son divisiones locales que operan en ubicaciones geográficas como la Rama Unicauca.</p>
                </details>

                <details class="faq-item">
                    <summary>¿Necesito ser miembro de IEEE para participar?</summary>
                    <p>Para acceder a todos los beneficios sí es necesario. Ofrecemos <strong>membresías de estudiante</strong> a costo reducido. Algunos eventos están abiertos a no-miembros. Contacta al capítulo para más detalles.</p>
                </details>

                <details class="faq-item">
                    <summary>¿Cuál es el costo de membresía?</summary>
                    <p>Los costos varían según tu categoría (estudiante, profesional, jubilado) y la sociedad. Ofrecemos <strong>descuentos especiales para estudiantes</strong>. Comunícate con nosotros para información detallada.</p>
                </details>

                <details class="faq-item">
                    <summary>¿Puedo ser miembro de múltiples capítulos?</summary>
                    <p>¡Absolutamente! Muchos profesionales participan en múltiples capítulos. No hay restricción para ser miembro activo de varias sociedades técnicas simultáneamente.</p>
                </details>
            </div>
